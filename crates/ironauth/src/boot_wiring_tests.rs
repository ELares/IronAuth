/// The public URL the harness config sets, from which the boot path derives the ONE
/// issuer base both planes take. A reserved TLD, so nothing here could resolve.
const PUBLIC_URL: &str = "https://boot-wiring.invalid";

/// The JWKS cache window the harness config sets, in seconds. Away from the shipped
/// default (600) and inside the validated 300 to 900 range, so the clamp both planes
/// apply is a no-op and cannot mask a divergence.
const JWKS_CACHE_MAX_AGE_SECS: u64 = 900;

/// The address of the object behind an `Arc`, which is what an identity contract means:
/// the two planes hold the SAME object, not an equal one.
fn address<T>(handle: &Arc<T>) -> usize {
    Arc::as_ptr(handle).addr()
}

/// One cross-plane value's probe.
///
/// A probe says what the fixture drove the value to and how to read it back off each
/// assembled plane state. It deliberately carries no statement of what an uninstalled
/// plane would report: that is OBSERVED, off the unwired pair, so it cannot drift.
struct SharedValueProbe {
    /// The declared name, which must match a [`SHARED_CONFIG_SECTION_NAMES`] or
    /// [`SHARED_BOOT_INPUT_NAMES`] entry.
    name: &'static str,
    /// For a config SECTION: TOML driving every key of the section away from its
    /// default. Empty for everything else, whose driving lives in the base harness
    /// config because its keys sit inside tables that config already opens. Which of
    /// the two applies is checked against the declaration, not left to this field.
    non_default_toml: &'static str,
    /// What the fixture says both planes should hold.
    expected: fn(&BootFixture) -> Value,
    /// What the OIDC data plane actually holds.
    on_oidc: fn(&OidcState) -> Value,
    /// What the management plane actually holds.
    on_admin: fn(&AdminState) -> Value,
    /// For a [`SHARED_OBJECT_NAMES`] subject: the address of the object the OIDC data
    /// plane holds. The harness compares the two addresses ITSELF, so a probe cannot
    /// satisfy the identity requirement with a predicate that ignores its arguments.
    oidc_object: Option<fn(&OidcState) -> Option<usize>>,
    /// The same, on the management plane.
    admin_object: Option<fn(&AdminState) -> Option<usize>>,
}

