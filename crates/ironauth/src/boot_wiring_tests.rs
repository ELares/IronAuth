//! The boot-wiring harness (issue #414): what the ASSEMBLED plane states hold.
//!
//! Before this, `crates/ironauth` had no test that observed a plane state. Its only
//! test drove a CLI subcommand as a subprocess, and both plane assemblies ended in an
//! opaque `Router`, so three silent boot-wiring failures were expressible for every
//! value both planes consume: dropping the install on the management plane, dropping it
//! on the data plane, and handing the two planes DIFFERENT values. Two of the three
//! built with zero warnings and the third was caught only incidentally, by
//! `unused_variable`.
//!
//! This suite assembles BOTH plane states from ONE config, through the REAL
//! [`assemble_planes`], against a real database and with no server and no listening
//! socket, and reads back what each plane actually holds.
//!
//! It drives [`assemble_planes`] rather than the two builders under it for a reason
//! that is the whole point of the suite: the discipline under test is that ONE capture
//! feeds BOTH planes. A harness that called the two builders itself would supply that
//! discipline by construction and then assert it, which proves nothing about the boot
//! path. Driving the one function that performs the capture makes the single carrier an
//! OBSERVED property of production code. Measured against a harness that called the two
//! builders: capturing twice with opposite ladder verdicts, handing one plane a freshly
//! built federation runtime, and swapping the capture site's two boolean arguments were
//! all green.
//!
//! The subject list is DERIVED, never written out here. It is
//! [`SHARED_CONFIG_SECTION_NAMES`] and [`SHARED_BOOT_INPUT_NAMES`], generated by the
//! same `shared_plane_inputs!` expansion that generates the install body itself;
//! [`SHARED_OBJECT_NAMES`] additionally REQUIRES an identity probe, and
//! [`SHARED_DERIVED_NAMES`] additionally requires that the subject be distinguishable
//! in EVERY run. A value declared there without a probe turns
//! [`every_declared_shared_value_has_a_probe`] red, and a probe naming a value that is
//! no longer declared turns it red too, so this suite cannot quietly stop covering a
//! shared value.
//!
//! Non-vacuity is OBSERVED, not asserted against a written constant: every probe is
//! also read off a pair of UNWIRED plane states, built by the same constructors from
//! the shipped default config with nothing installed, and the driven value must differ
//! from what those report. A written "what an uninstalled plane reports" constant can
//! agree with the state struct's real default by coincidence and then quietly stop
//! agreeing. Measured with such a constant in place: changing the states' uninstalled
//! `max_group_depth` to the driven value, or flipping the states' default
//! `signup_quarantine_enabled` to true, disarmed the guard entirely while every test
//! stayed green.
//!
//! One honest limit to record: this suite issues NO management-plane query. It proves
//! what each plane HOLDS, and (through the control-plane DSN) that the management plane
//! authenticates as the separate control credential, but it exercises none of that
//! role's grants.

